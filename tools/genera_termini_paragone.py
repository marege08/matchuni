# -*- coding: utf-8 -*-
"""Regenerate termini-paragone.js: the values a course score is ranked against.

WHY IT EXISTS: the Base view scores every column from 0 to 10 by its rank
among comparable sheets. Universities and groups are ranked against the
other aggregates in almalaurea.sqlite, which the browser already holds. A
course is ranked against the first-level courses of its discipline group
across Italy, and those live in 78 per-university databases that the browser
downloads one at a time: ranking a course would mean downloading all of
them. This module carries the needed values instead, a few tens of kilobytes.

WHAT IT DOES: for each key indicator of the summary (INDICATORI_CRUSCOTTO in
frontend/public/js/indicatori-chiave.js, read from that file so the two can
never disagree), it collects the value of every course with at least
SOGLIA_RISPONDENTI respondents in the indicator's survey, grouped by
discipline group and, for the employment survey, by definition of
"employed". Values are copied, never recomputed, with one exception:

  "lavora-studia", the share of graduates who work or are enrolled in a
  second-level degree, is the sum of the three positive answers of
  "Condizione occupazionale e formativa (%)". For first-level graduates the
  plain employment rate is misleading, because most of them go on to a
  second-level degree and are counted as not working. A "zero_casi" answer
  counts as 0; an answer hidden by the source (fewer than 5 cases) makes the
  sum unknown, and the course is left out rather than estimated.

USAGE:
    python3 tools/genera_termini_paragone.py            # writes the module
    python3 tools/genera_termini_paragone.py --check    # does not write; only checks
"""

import argparse
import json
import re
import sqlite3
import sys
from pathlib import Path

RADICE = Path(__file__).resolve().parent.parent
CORSI_SITO = RADICE / "frontend" / "public" / "corsi"
INDICATORI_CHIAVE = RADICE / "frontend" / "public" / "js" / "indicatori-chiave.js"
USCITA = RADICE / "frontend" / "public" / "js" / "termini-paragone.js"

# Same threshold as SOGLIA_CAMPIONE_PICCOLO in app.js: below it a value is
# too unstable to rank anything against.
SOGLIA_RISPONDENTI = 40

# Definitions of "employed" published for the employment survey.
DEFINIZIONI = ("ampia", "restrittiva")

CATEGORIA_LAVORA_STUDIA = "Condizione occupazionale e formativa (%)"
VOCI_LAVORA_STUDIA = (
    "Lavorano e non sono iscritti ad una laurea di secondo livello",
    "Lavorano e sono iscritti ad una laurea di secondo livello",
    "Non lavorano e sono iscritti ad una laurea di secondo livello",
)

INTESTAZIONE = """/**
 * termini-paragone.js
 *
 * Values a course is ranked against to compute its 0-10 score (js/voto.js):
 * for each key indicator, the value of every course with at least {soglia}
 * respondents, by discipline group, sorted. Employment indicators have one
 * list per definition of "employed". A course is ranked only against courses
 * of its own type: "valori" holds the first-level courses, "valoriCicloUnico"
 * the single-cycle ones.
 *
 * {corsi} first-level and {corsi_lse} single-cycle courses from {atenei}
 * universities, read from frontend/public/corsi/. "lavora-studia" (first-level
 * courses only) is the sum of the three positive answers of "{categoria}";
 * every other value is copied as published.
 *
 * Regenerated by tools/genera_termini_paragone.py, not edited by hand.
 */
"""


def apri_sola_lettura(percorso):
    """Open a SQLite database read-only.

    Args:
        percorso: Database path.

    Returns:
        A read-only SQLite connection.
    """
    # as_uri() encodes characters such as '?' that would otherwise be read as
    # URI parameters and silently open a different file.
    return sqlite3.connect(f"{percorso.resolve().as_uri()}?mode=ro", uri=True)


def leggi_indicatori():
    """Read the key indicators from indicatori-chiave.js.

    Only the INDICATORI_CRUSCOTTO array is read. Each entry must carry id,
    indagine, categoria and indicatore as plain string literals; anything
    else stops the run instead of being guessed.

    Returns:
        A list of dicts with id, indagine, categoria and indicatore.
    """
    testo = INDICATORI_CHIAVE.read_text(encoding="utf-8")
    blocco = re.search(r"export const INDICATORI_CRUSCOTTO = \[(.*?)\n\];", testo, re.S)
    if not blocco:
        sys.exit(f"INDICATORI_CRUSCOTTO non trovato in {INDICATORI_CHIAVE.name}")
    letterale = r"""'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)\""""
    indicatori = []
    for oggetto in re.findall(r"\{(.*?)\n  \}", blocco.group(1), re.S):
        campi = {}
        for nome, singolo, doppio in re.findall(rf"(\w+): (?:{letterale})", oggetto):
            campi[nome] = (singolo or doppio).replace("\\'", "'").replace('\\"', '"')
        mancanti = {"id", "indagine", "categoria", "indicatore"} - campi.keys()
        if mancanti:
            sys.exit(f"Indicatore senza {sorted(mancanti)} in {INDICATORI_CHIAVE.name}: {oggetto.strip()[:80]}")
        indicatori.append({k: campi[k] for k in ("id", "indagine", "categoria", "indicatore")})
    if not indicatori:
        sys.exit(f"Nessun indicatore letto da {INDICATORI_CHIAVE.name}")
    return indicatori


def aggiungi(valori, chiave, gruppo, valore):
    """Append a value to valori[chiave][gruppo], creating the lists on demand."""
    valori.setdefault(chiave, {}).setdefault(gruppo, []).append(valore)


def leggi_corsi(indicatori, tipo_corso="L"):
    """Collect the ranked values from every course database.

    Args:
        indicatori: Key indicators from leggi_indicatori().
        tipo_corso: 'L' (first level) or 'LSE' (single cycle). Only first-level
            courses get "lavora-studia": single-cycle graduates have finished
            their studies, so their plain employment rate is not misleading.

    Returns:
        (valori, corsi, atenei): valori is {"profilo": {id: {gruppo: [..]}},
        "occupazione": {definizione: {id: {gruppo: [..]}}}}; corsi and
        atenei count the databases and courses read.
    """
    valori = {"profilo": {}, "occupazione": {d: {} for d in DEFINIZIONI}}
    corsi = set()
    database = sorted(CORSI_SITO.glob("*.sqlite"))
    if not database:
        sys.exit(f"Nessun database dei corsi in {CORSI_SITO}")
    for percorso in database:
        conn = apri_sola_lettura(percorso)
        try:
            for ind in indicatori:
                righe = conn.execute(
                    """SELECT ateneo, corso, gruppo, definizione, valore, numero_compilatori
                       FROM dati
                       WHERE tipo_corso = ? AND indagine = ? AND categoria = ? AND indicatore = ?""",
                    (tipo_corso, ind["indagine"], ind["categoria"], ind["indicatore"]),
                ).fetchall()
                for ateneo, corso, gruppo, definizione, valore, rispondenti in righe:
                    corsi.add((ateneo, corso))
                    if valore is None or (rispondenti or 0) < SOGLIA_RISPONDENTI:
                        continue
                    if ind["indagine"] == "profilo":
                        aggiungi(valori["profilo"], ind["id"], gruppo, valore)
                    elif definizione in DEFINIZIONI:
                        aggiungi(valori["occupazione"][definizione], ind["id"], gruppo, valore)
                    else:
                        # 'condivisa' rows hold for both definitions.
                        for d in DEFINIZIONI:
                            aggiungi(valori["occupazione"][d], ind["id"], gruppo, valore)

            if tipo_corso != "L":
                continue
            per_corso = {}
            for corso, gruppo, definizione, voce, valore, nota, rispondenti in conn.execute(
                """SELECT corso, gruppo, definizione, indicatore, valore, nota, numero_compilatori
                   FROM dati
                   WHERE tipo_corso = 'L' AND indagine = 'occupazione' AND categoria = ?""",
                (CATEGORIA_LAVORA_STUDIA,),
            ):
                per_corso.setdefault((corso, definizione), (gruppo, rispondenti, []))[2].append(
                    (voce, valore, nota))
            for (corso, definizione), (gruppo, rispondenti, voci) in per_corso.items():
                if definizione not in DEFINIZIONI or (rispondenti or 0) < SOGLIA_RISPONDENTI:
                    continue
                somma = lavora_o_studia(voci)
                if somma is not None:
                    aggiungi(valori["occupazione"][definizione], "lavora-studia", gruppo, somma)
        finally:
            conn.close()
    return valori, len(corsi), len(database)


def lavora_o_studia(voci):
    """Sum the positive answers of one course, or None when it is unknown.

    Args:
        voci: (indicatore, valore, nota) tuples of the course's
            "Condizione occupazionale e formativa (%)" rows.

    Returns:
        The sum rounded to one decimal, or None when every answer is missing
        or a positive answer is hidden by the source.
    """
    if all(valore is None for _, valore, _ in voci):
        return None
    somma = 0.0
    for voce, valore, nota in voci:
        if voce not in VOCI_LAVORA_STUDIA:
            continue
        if valore is not None:
            somma += valore
        elif nota != "zero_casi":
            return None
    return round(somma, 1)


def ordina(valori):
    """Sort every list and the keys, so the output is stable between runs."""
    if isinstance(valori, list):
        return sorted(valori)
    return {k: ordina(valori[k]) for k in sorted(valori, key=lambda k: (len(k), k))}


def rendi(indicatori, valori, corsi, atenei, valori_lse, corsi_lse):
    """Render the JavaScript module.

    Args:
        indicatori: Key indicators.
        valori: Values of the first-level courses, from leggi_corsi().
        corsi: Number of first-level courses read.
        atenei: Number of university databases read.
        valori_lse: Values of the single-cycle courses.
        corsi_lse: Number of single-cycle courses read.

    Returns:
        The module text.
    """
    contenuto = {
        "soglia": SOGLIA_RISPONDENTI,
        "indicatori": [{k: i[k] for k in ("id", "indagine", "categoria", "indicatore")} for i in indicatori],
        "lavoraStudia": {"categoria": CATEGORIA_LAVORA_STUDIA, "voci": list(VOCI_LAVORA_STUDIA)},
        "valori": ordina(valori),
        "valoriCicloUnico": ordina(valori_lse),
    }
    testo = INTESTAZIONE.format(soglia=SOGLIA_RISPONDENTI, corsi=f"{corsi:,}".replace(",", "."),
                                corsi_lse=f"{corsi_lse:,}".replace(",", "."),
                                atenei=atenei, categoria=CATEGORIA_LAVORA_STUDIA)
    testo += "\nexport const TERMINI_PARAGONE = "
    testo += json.dumps(contenuto, ensure_ascii=False, separators=(",", ":"))
    return testo + ";\n"


def main():
    """Parse arguments and write or check the module."""
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="non scrive nulla: esce con codice 1 se il modulo non corrisponde ai dati")
    argomenti = parser.parse_args()

    indicatori = leggi_indicatori()
    valori, corsi, atenei = leggi_corsi(indicatori, "L")
    valori_lse, corsi_lse, _ = leggi_corsi(indicatori, "LSE")
    for etichetta, v in (("triennali", valori), ("ciclo unico", valori_lse)):
        for indagine, chiavi in (("profilo", v["profilo"]),
                                 *((f"occupazione/{d}", v["occupazione"][d]) for d in DEFINIZIONI)):
            quanti = {k: sum(len(x) for x in g.values()) for k, g in sorted(chiavi.items())}
            print(f"{etichetta}, {indagine}: {quanti}")
    testo = rendi(indicatori, valori, corsi, atenei, valori_lse, corsi_lse)

    nome = USCITA.relative_to(RADICE)
    if argomenti.check:
        if USCITA.exists() and USCITA.read_text(encoding="utf-8") == testo:
            print(f"OK: {nome} corrisponde ai dati.")
            return 0
        print(f"DIVERSO: {nome} non corrisponde ai dati.")
        return 1
    USCITA.write_text(testo, encoding="utf-8")
    print(f"Scritto {nome} ({len(testo.encode('utf-8')):,} byte)".replace(",", "."))
    return 0


if __name__ == "__main__":
    sys.exit(main())
